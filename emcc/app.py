"""Application shell: title bar, sub-header, scrolling device list, event pump.

Threading model
---------------
Everything in this module runs on the Tk main thread. Worker threads never
touch a widget; they put `DeviceEvent` values on a queue which `_pump` drains
on a timer, applies to backend state, and then renders. That is the only path
by which network activity reaches the UI.

    ConnectionWorker thread -> Queue -> _pump (Tk thread) -> card.render()

Window chrome
-------------
The design draws its own title bar, so the native caption has to go. Rather
than `overrideredirect(True)` -- which also costs taskbar presence, snap,
minimise animation and resize borders, all of which then need reimplementing --
this clears only WS_CAPTION from the window style via ctypes and keeps
WS_THICKFRAME. The result is a captionless window that Windows still treats as
a normal one, so resizing and snapping keep working and the traffic lights only
have to drive close/minimise/maximise.

`overrideredirect` remains a fallback for non-Windows, where the app is not
targeted but should still start.
"""

