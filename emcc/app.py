#: Attributes that `tests/` and `tools/visual_pass.py` reach on `App` from
#: outside, minus the seven that resolve on `customtkinter.CTk` and so never
#: reach `__getattr__` at all. The four-slice modularisation moves the code
#: behind several of these into `shell/` and `views/`; each must stay
#: reachable on `App` under its current name, because 174 call sites outside
#: `emcc/` use them and are not being rewritten.
#:
#: Generated by the scan in `test_facade_covers_every_name_reached_from_outside`
#: rather than typed. This list was wrong three times in one day -- 19, 24 and
#: 26 all in circulation -- and every time the wrongness was silent, because
#: nothing failed when it drifted. That test is what keeps it honest; do not
#: hand-edit this set without running it.
_FACADE_NAMES: frozenset[str] = frozenset({
    "_add_device", "_build_remaining", "_caption", "_cards",
    "_clean_device", "_confirm_remove", "_connect_device", "_hint",
    "_list", "_logo", "_order", "_pending_devices", "_pump",
    "_refresh_chrome", "_remove_device", "_render_device",
    "_scroll_to_end", "_shutting_down", "_toggle_auto",
    "config_manager", "manager", "shutdown", "title_bar",
    # Added by the Dashboard mount. `views` is the host, `_sub` the
    # sub-header builder, `_switch_view` the toggle's adapter -- all three
    # are reached from `tests/` now, so the same obligation applies to them
    # as to the older names: a slice that moves one must leave it reachable.
    # The completeness test demanded these rather than my noticing.
    "_sub", "_switch_view", "views"
})


class App(ctk.CTk):
    #: The facade contract, as a class attribute so callers reach it as
    #: `App._FACADE`. Same frozenset object as the module-level
    #: `_FACADE_NAMES`, which is what `__getattr__` reads -- it consults the
    #: module global rather than `self._FACADE` deliberately, since an
    #: attribute lookup inside `__getattr__` is how you get infinite
    #: recursion the first time the attribute is genuinely absent.
    _FACADE = _FACADE_NAMES

    def __init__(self, config: ConfigManager | None = None):
        super().__init__(fg_color=theme.APP_BG)

        self.title(theme.APP_TITLE)
        self.geometry(f"{theme.WINDOW_W}x{theme.WINDOW_H}")
        self.minsize(theme.WINDOW_MIN_W, theme.WINDOW_MIN_H)

        # A new Tk interpreter invalidates every cached CTkImage and CTkFont
        # (they hold interpreter-owned handles), so drop both caches before any
        # widget is built. See the note in icons.py.
        icons.clear_cache()
        fonts.clear_cache()
        fonts.init()

        self.config_manager = config or ConfigManager()
        if config is None:
            self.config_manager.load()
        self.config_manager.on_save_error = self._on_config_save_error

        # DeviceManager owns the timers but not Tk: it gets a scheduler.
        self.manager = DeviceManager(
            self.config_manager,
            schedule=lambda delay_ms, fn: self.after(delay_ms, fn),
            cancel=self.after_cancel,
        )
        # Composed deliberately: an event means repaint *and* announce.
        # `_render_device` alone no longer announces -- see shell/pump.py.
        self.manager.on_device_changed = self._on_device_changed

        #: Set by the `list` factory before the host sends `set_devices`,
        #: which is what makes the facade properties below safe during
        #: construction -- see the wiring-order rule in VIEW_CONTRACT.md.
        self._list_view: ListView | None = None
        self._offsets: dict[bool, float] = {}
        #: Variants with a measurement already queued, so a card that
        #: re-renders before it lands cannot pile up callbacks.
        self._measuring: set[bool] = set()
        self._drag_origin = (0, 0)
        self._maximised = False
        self._shutting_down = False
        self._pump_job: str | None = None
        self._errors = ErrorReporter(self)
        self._splash: LaunchSplash | None = None
        self._splash_job: str | None = None
        self._splash_deadline = 0.0
        self._splash_ready_polls = 0

        self._strip_caption()

        self.title_bar = TitleBar(
            self,
            on_close=self.shutdown,
            on_minimise=self._minimise,
            on_maximise=self._toggle_maximise,
            on_drag_start=self._drag_start,
            on_drag_move=self._drag_move,
        )
        self.title_bar.pack(fill="x")

        self._build_subheader()
        self._build_views()

        # Alt+F4 and any OS-level close must run the same teardown as the
        # traffic light, or shutdown is silently skipped.
        self.protocol("WM_DELETE_WINDOW", self.shutdown)
        self._start_pump()

        # Pre-render the launch splash off the UI thread. ~390ms of pure
        # Pillow work, deliberately not done on click: the splash has to
        # appear the instant the operator asks for it.
        self.after(500, splash_module.prepare)

